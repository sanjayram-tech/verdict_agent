"""Render report.md / decisions.json / metrics.json from a RunResult."""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .agent import RunResult
from .text import md_escape

ADVISORY = ("> **Decision support, not an approval.** Generated by an AI agent from Jira records; a human "
            "release manager must review and sign off.")


def _cite(ref: str, index: dict[str, dict[str, Any]], base_url: str | None) -> str:
    c = index.get(ref)
    if not c:
        return f"`{md_escape(ref)}`"
    key = c["issue_key"]
    link = f"{base_url}/browse/{key}?focusedCommentId={ref.split('#c', 1)[1]}" if base_url else None
    head = f"`{ref}`" + (f" ([open]({link}))" if link else "")
    who = f"{md_escape(c['actor'] or '?')} ({md_escape(c['role'] or '?')}), recorded {md_escape(c['recorded_at'] or '?')}"
    return f"{head} · {md_escape(c.get('source_id') or '?')} · {who}: “{md_escape(c['text'], 260)}”"


def render_markdown(run: RunResult, index: dict[str, dict[str, Any]], project: str, label: str,
                    base_url: str | None = None) -> str:
    lines: list[str] = []
    t = run.target or {}
    lines += ["# Release readiness report", ""]
    lines += [ADVISORY, ""]
    lines += [f"- **Overall decision:** **{run.verdict or 'NOT DETERMINED (' + run.status + ')'}**",
              f"- **Run status:** {run.status}",
              f"- **Target:** release `{t.get('release')}`, commit `{t.get('commit')}`, prompt `{t.get('prompt')}`, "
              f"environment `{t.get('environment')}`, service `{t.get('service')}`",
              f"- **Scope:** Jira project `{project}`, label `{label}`",
              f"- **Generated:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} · model "
              f"`{run.metrics.get('provider')}:{run.metrics.get('model')}`", ""]
    lines += ["Overall rule (computed in code): any FAIL → BLOCKED; otherwise any INSUFFICIENT_EVIDENCE → "
              "NEEDS_REVIEW; only all PASS → READY.", ""]

    lines += ["## Summary", "", "| Requirement | Decision | Summary |", "|---|---|---|"]
    for r in run.requirements:
        flag = " ⚠" if r.agent_failure else ""
        lines.append(f"| {r.id} ({r.key}) | **{r.decision}**{flag} | {md_escape(r.summary)} |")
    counts = {d: sum(1 for r in run.requirements if r.decision == d) for d in ("PASS", "FAIL", "INSUFFICIENT_EVIDENCE")}
    lines += ["", f"PASS {counts['PASS']} · FAIL {counts['FAIL']} · INSUFFICIENT_EVIDENCE "
                  f"{counts['INSUFFICIENT_EVIDENCE']}", ""]

    lines += ["## Requirement decisions", ""]
    for r in run.requirements:
        lines += [f"### {r.id} — {md_escape(r.summary)}: {r.decision}", "",
                  f"- **Jira:** {r.key}", f"- **Acceptance criterion:** {md_escape(r.criterion)}", "",
                  "**Explanation.** " + md_escape(r.rationale), ""]
        if r.evidence_refs:
            lines += ["**Evidence cited:**", ""]
            lines += [f"- {_cite(ref, index, base_url)}" for ref in r.evidence_refs]
            lines.append("")
        lines += ["**Outstanding verification / clarification:**", ""]
        lines += [f"- {md_escape(o)}" for o in r.outstanding] or ["- None"]
        lines.append("")
        if r.agent_failure:
            lines += [f"> ⚠ Agent failure: {md_escape(r.agent_failure)}", ""]
        if r.guardrail_rejections:
            lines += ["<details><summary>Guardrail rejections before the accepted decision</summary>", ""]
            lines += [f"- {md_escape(p)}" for p in r.guardrail_rejections]
            lines += ["", "</details>", ""]

    lines += ["## Suspicious content found in Jira records", ""]
    if run.suspicious:
        lines.append("Instruction-like text aimed at reviewers was detected and treated as untrusted data "
                     "(it did not change any rule or decision automatically):")
        lines.append("")
        for s in run.suspicious:
            lines.append(f"- `{s['ref']}` ({md_escape(s.get('source_id') or '?')}, {md_escape(s.get('actor') or '?')} / "
                         f"{md_escape(s.get('role') or '?')}, recorded {md_escape(s.get('recorded_at') or '?')}): "
                         f"“{md_escape(s['text'], 300)}”")
    else:
        lines.append("None detected.")
    lines.append("")

    lines += ["## Failures and warnings", ""]
    fails = [f"- {r.id}: {md_escape(r.agent_failure)}" for r in run.requirements if r.agent_failure]
    fails += [f"- {md_escape(w)}" for w in run.warnings]
    lines += fails or ["- None. All tool and model calls completed (retries, if any, are in trace.jsonl)."]
    lines.append("")

    m = run.metrics
    tok = m.get("tokens", {})
    lines += ["## Run metrics", "",
              f"- Wall time: {m.get('wall_time_s')} s",
              f"- Model: `{m.get('provider')}:{m.get('model')}` · model calls: {m.get('model_calls')}",
              f"- Tokens: prompt {tok.get('prompt')}, output {tok.get('output')}, thinking {tok.get('thoughts')}, "
              f"total {tok.get('total')}",
              f"- Tool calls: {m.get('tool_calls')} (errors {m.get('tool_errors')}, cache hits {m.get('cache_hits')})",
              "", "| Requirement | Tool calls | Model turns | Total tokens | Seconds |", "|---|---|---|---|---|"]
    for rid, v in m.get("per_requirement", {}).items():
        lines.append(f"| {rid} | {v['tool_calls']} | {v['model_turns']} | {v['tokens']['total']} | {v['wall_s']} |")
    lines += ["", "Native Jira authors and timestamps reflect the importer; actor, role and time above are the "
                  "recorded scenario values quoted from the record text.", ""]
    return "\n".join(lines)


def decisions_json(run: RunResult) -> dict[str, Any]:
    return {"status": run.status, "verdict": run.verdict, "target": run.target,
            "requirements": [{"id": r.id, "key": r.key, "decision": r.decision, "evidence_refs": r.evidence_refs,
                              "outstanding": r.outstanding, "rationale": r.rationale,
                              "agent_failure": r.agent_failure, "guardrail_rejections": r.guardrail_rejections}
                             for r in run.requirements]}


def write_outputs(run: RunResult, out_dir: Path, index: dict[str, dict[str, Any]], project: str, label: str,
                  base_url: str | None) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "report.md").write_text(render_markdown(run, index, project, label, base_url), encoding="utf-8")
    (out_dir / "decisions.json").write_text(json.dumps(decisions_json(run), indent=2), encoding="utf-8")
    (out_dir / "metrics.json").write_text(json.dumps(run.metrics, indent=2), encoding="utf-8")
